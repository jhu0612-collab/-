import streamlit as st

from lib.state import render_api_key_sidebar

st.set_page_config(page_title="해구대 소싱 자동화", page_icon="📦", layout="wide")

render_api_key_sidebar()

st.title("📦 해구대 소싱 자동화 도구")

st.markdown(
    """
셀럭홈즈(셀러라이프) 엑셀 → 픽투셀 업로드 전 단계까지를 도와주는 도구예요.
왼쪽 목록에서 아래 순서대로 페이지를 클릭해서 사용하시면 돼요. (왼쪽에 목록이 안 보이면 화면 왼쪽 위 `>` 화살표를 눌러보세요)

---
"""
)

with st.expander("① 📊 카테고리 필터링 — 여기부터 시작하세요", expanded=True):
    st.markdown(
        """
        1. 왼쪽 목록에서 **`📊 카테고리 필터링`** 클릭
        2. 화면 중간의 **"Browse files" 버튼**을 눌러서 셀러라이프에서 받은 엑셀 파일 선택
        3. 잠시 기다리면 자동으로 조건에 맞는 후보 표가 나와요 (조건은 화면 위쪽 숫자칸에서 바꿀 수 있어요)
        4. 마음에 들면 **"필터링 결과 CSV 다운로드"** 버튼으로 저장해도 되고, 그냥 다음 페이지로 넘어가도 돼요 (자동으로 기억해둬요)
        """
    )

with st.expander("② 🤖 AI 카테고리 추천 — Claude 키 필요"):
    st.markdown(
        """
        1. ①번을 먼저 실행해야 여기서 이어서 쓸 수 있어요
        2. **"AI 추천 받기"** 버튼만 누르면 끝이에요
        3. 잠시 기다리면 AI가 추천 키워드와 이유를 글로 설명해줘요
        """
    )

with st.expander("③ 🈶 키워드 번역 — Claude 키 필요"):
    st.markdown(
        """
        1. ②번에서 고른 키워드를 **"한국어 키워드"** 칸에 입력
        2. **"번역하기"** 버튼 클릭 → 중국어 번역 결과가 나와요
        3. 복사할 필요 없어요 — **⑥번 자동수집 페이지에 자동으로 넘어가요** (검색어, 카테고리 매칭용 한국어 키워드 둘 다)
        """
    )

with st.expander("⑥ 🕷️ 자동수집 통합 — 여기가 핵심, Apify 토큰 필요", expanded=True):
    st.markdown(
        """
        1. ③번에서 번역한 중국어 키워드와 가격범위를 입력하고 **"① 타오바오 검색·수집 실행"** 클릭
        2. 상품 목록이 나오면 **"예상무게(kg)"** 칸을 직접 수정 (타오바오 검색결과엔 무게정보가 없어서 대략 추산해서 입력해요)
        3. 배송방식·포장방식 확인하고 **"② 배송비 계산 + 리스크체크 실행"** 클릭 → 무게 기준 배송비가 계산되고 위험여부가 나와요 (원가×마진율 계산은 픽투셀이 자체 설정대로 알아서 해요)
        4. 위험한 상품은 자동 제외하고, 필요하면 카테고리 코드도 자동매칭한 뒤 **"③ 픽투셀 양식 엑셀 만들기"** 클릭 → 다운로드
        5. 다운받은 엑셀을 **픽투셀 '엑셀로 일괄등록' 화면에 드래그**하면 등록 끝! (배송비는 "추가마진"으로 들어가서 고객한텐 안 보여요)
        """
    )

with st.expander("④ 💰 마진·가격 계산기 (개별 확인용) — 키 없이도 사용 가능"):
    st.markdown(
        """
        상품 하나만 빠르게 계산해보고 싶을 때 쓰는 보조 도구예요. 원가(위안)·무게를 넣으면 최종판매가가 바로 나와요.
        (⑥번 자동수집을 쓰면 이 계산이 자동으로 같이 되니, 평소엔 ⑥번만 써도 충분해요)
        """
    )

with st.expander("⑤ 🚫 리스크 필터 (개별 확인용) — 키 없이도 사용 가능"):
    st.markdown(
        """
        상품명 하나만 빠르게 위험 키워드 체크하고 싶을 때 쓰는 보조 도구예요.
        (⑥번 자동수집에도 이 체크가 자동으로 포함돼 있어요)
        """
    )

st.markdown(
    """
---
①~③번으로 카테고리·키워드를 정하고, **⑥번 자동수집 통합 페이지**에서 검색부터 픽투셀 업로드용 엑셀까지 한번에 처리하면 돼요.
그 엑셀을 픽투셀에 드래그하면 등록 끝이에요.

💡 필요한 API 키는 **Claude(②③번) + Apify(⑥번)** 두 개예요. ①④⑤번은 키 없이 바로 쓸 수 있어요.
한번 입력한 키는 이 컴퓨터에 자동 저장돼서, 프로그램을 껐다 켜도 다시 입력할 필요 없어요.
"""
)
